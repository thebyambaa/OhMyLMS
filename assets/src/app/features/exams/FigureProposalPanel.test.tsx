import { configure, fireEvent, render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import * as api from './api';
import FigureProposalPanel from './FigureProposalPanel';
import { job, triangle } from './fixtures';
import type { ImportFigure, ImportJobDetail } from './types';

vi.mock( './api', () => ( {
	proposeFigure: vi.fn(),
	decideProposal: vi.fn(),
} ) );

configure( { asyncUtilTimeout: 5000 } );

const figure: ImportFigure = {
	id: 'f1',
	page: 1,
	bounds: [ 0, 0, 1, 1 ],
	part_ids: [],
	asset_id: '9f0a7c52-6c3e-4a4e-9a55-1f4e2b2c8d11',
	alt: 'Triangle ABC',
	not_to_scale: true,
	selected: 'original',
	approved: false,
};
const proposed: ImportFigure = {
	...figure,
	proposal: {
		status: 'proposed',
		origin: 'generated',
		display: 'replace',
		spec: triangle,
	},
};

function renderPanel(
	value: ImportFigure,
	options: { canGenerate?: boolean; dirty?: boolean } = {}
) {
	const onRun = vi.fn(
		(
			work: ( signal: AbortSignal ) => Promise< ImportJobDetail >,
			done: string
		) => {
			void work( new AbortController().signal );
			return done;
		}
	);
	render(
		<FigureProposalPanel
			jobId={ 7 }
			rowIndex={ 0 }
			revision={ 3 }
			figure={ value }
			cropUrl="https://example.test/crop.png"
			canGenerate={ options.canGenerate ?? false }
			dirty={ options.dirty ?? false }
			busy={ false }
			onRun={ onRun }
		/>
	);
	return onRun;
}

beforeEach( () => {
	vi.resetAllMocks();
	vi.mocked( api.proposeFigure ).mockResolvedValue( job );
	vi.mocked( api.decideProposal ).mockResolvedValue( job );
} );

describe( 'FigureProposalPanel', () => {
	it( 'checks an authored configuration before proposing it', async () => {
		const user = userEvent.setup();
		renderPanel( figure );
		expect(
			screen.getByText( 'No reconstruction proposed yet.' )
		).toBeInTheDocument();
		expect(
			screen.queryByRole( 'button', { name: /exam converter/ } )
		).toBeNull();
		const source = screen.getByRole( 'textbox', {
			name: 'Configuration (JSON)',
		} );
		fireEvent.change( source, { target: { value: '{"version":1' } } );
		await user.click(
			screen.getByRole( 'button', { name: 'Propose this configuration' } )
		);
		expect( screen.getByRole( 'alert' ) ).toHaveTextContent(
			'not valid JSON'
		);
		expect( api.proposeFigure ).not.toHaveBeenCalled();
		fireEvent.change( source, {
			target: { value: JSON.stringify( triangle ) },
		} );
		await user.click(
			screen.getByRole( 'button', { name: 'Propose this configuration' } )
		);
		expect( api.proposeFigure ).toHaveBeenCalledWith(
			7,
			0,
			'f1',
			3,
			triangle,
			expect.any( AbortSignal )
		);
	} );
	it( 'generates with the configured converter', async () => {
		const user = userEvent.setup();
		renderPanel( figure, { canGenerate: true } );
		await user.click(
			screen.getByRole( 'button', {
				name: 'Generate with the exam converter',
			} )
		);
		expect( api.proposeFigure ).toHaveBeenCalledWith(
			7,
			0,
			'f1',
			3,
			'generate',
			expect.any( AbortSignal )
		);
	} );
	it( 'compares, edits labels, accepts or rejects a proposal', async () => {
		const user = userEvent.setup();
		renderPanel( proposed );
		expect( screen.getByRole( 'status' ) ).toHaveTextContent(
			'Proposed (generated by the exam converter)'
		);
		const preview = document.querySelector(
			'figure.ohmylms-import-figure[data-figure-spec]'
		);
		expect(
			JSON.parse( preview?.getAttribute( 'data-figure-spec' ) ?? '' )
		).toEqual( triangle );
		// The original beside the reconstruction, which keeps it as its fallback.
		expect( screen.getAllByAltText( 'Triangle ABC' ) ).toHaveLength( 2 );
		const label = screen.getByRole( 'textbox', {
			name: 'Label of point B',
		} );
		await user.clear( label );
		await user.type( label, 'B2' );
		await user.click(
			screen.getByRole( 'button', { name: 'Save labels' } )
		);
		expect( api.proposeFigure ).toHaveBeenCalledWith(
			7,
			0,
			'f1',
			3,
			expect.objectContaining( {
				objects: expect.arrayContaining( [
					expect.objectContaining( { id: 'B', label: 'B2' } ),
				] ),
			} ),
			expect.any( AbortSignal )
		);
		await user.click(
			screen.getByRole( 'button', {
				name: 'Accept instead of the original',
			} )
		);
		await user.click(
			screen.getByRole( 'button', { name: 'Accept beside the original' } )
		);
		await user.click( screen.getByRole( 'button', { name: 'Reject' } ) );
		expect(
			vi
				.mocked( api.decideProposal )
				.mock.calls.map( ( call ) => call[ 4 ] )
		).toEqual( [ 'replace', 'accompany', 'reject' ] );
	} );
	it( 'disables an accepted choice and waits for unsaved row edits', () => {
		renderPanel(
			{
				...proposed,
				selected: 'both',
				spec: triangle,
				proposal: {
					...proposed.proposal!,
					status: 'accepted',
					display: 'accompany',
				},
			},
			{ dirty: true }
		);
		expect(
			screen.getByText( /Save or discard the changes/ )
		).toBeInTheDocument();
		expect(
			screen.getByRole( 'button', { name: 'Accept beside the original' } )
		).toBeDisabled();
		expect(
			screen.getByRole( 'button', { name: 'Reject' } )
		).toBeDisabled();
		expect(
			screen.getByRole( 'textbox', { name: 'Configuration (JSON)' } )
		).toBeDisabled();
	} );
} );
