const ownerTargets = {
	'shared-infrastructure': 'named shared module (step 3)',
	'WordPress platform': 'direct `@wordpress/*` / `@wordpress/element` import',
	'vendor-packages': '`assets/src/features/vendor-packages`',
};

const escapeCell = ( value ) =>
	String( value ?? '' )
		.replace( /\|/g, '\\|' )
		.replace( /\n/g, ' ' );
const table = ( head, rows ) =>
	[
		`| ${ head.join( ' | ' ) } |`,
		`| ${ head.map( () => '---' ).join( ' | ' ) } |`,
		...rows.map(
			( row ) => `| ${ row.map( escapeCell ).join( ' | ' ) } |`
		),
	].join( '\n' );
const kb = ( bytes ) =>
	`${ Math.max( 1, Math.round( bytes / 1024 ) ).toLocaleString(
		'en-US'
	) } KB`;
const code = ( value ) => `\`${ value }\``;
const count = ( list, predicate ) => list.filter( predicate ).length;

function describe( dependency ) {
	switch ( dependency.kind ) {
		case 'platform':
			return dependency.package;
		case 'feature-component':
			return `${ dependency.feature }/${ dependency.component }`;
		case 'vendor':
			return `${ dependency.library } (factory ${ dependency.id })`;
		case 'lms-module':
			return `${ dependency.hint } (factory ${ dependency.id })`;
		case 'recovered-local':
			return `${ dependency.purpose } in ${ path.basename(
				dependency.fragment || '?'
			) }`;
		default:
			return dependency.kind;
	}
}

/** Markdown report; deterministic so `--check` can detect drift. */
export function renderInventory( inventory ) {
	const { dependencies, components, libraries, application } = inventory;
	const live = dependencies.filter(
		( dependency ) => dependency.owner !== 'build tooling'
	);
	const features = [
		...new Set( components.map( ( component ) => component.feature ) ),
	].sort();
	const lines = [
		'# Runtime dependency inventory',
		'',
		'<!-- Generated by `node tools/runtime-inventory-report.mjs --write`. Do not edit by hand. -->',
		'',
		'Roadmap step 1. This lists everything authored features still receive through `readRuntime()`',
		'from recovered application factory 1841, plus every recovered library family the shipped',
		'bundles still register. Each entry has an owner and the roadmap step that removes it. For the',
		'steps and acceptance criteria, see [the modularization roadmap](MODULARIZATION-ROADMAP.md).',
		'',
		'## Summary',
		'',
		table(
			[ 'Measure', 'Count' ],
			[
				[
					'Application fragments in factory 1841',
					application.fragments,
				],
				[ 'Top-level bindings in factory 1841', application.bindings ],
				[ 'Routes in the recovered router', application.routes ],
				[
					'Authored components created through `readRuntime`',
					components.length,
				],
				[
					'Distinct bindings those components read',
					dependencies.length,
				],
				[
					'… authored feature components',
					count(
						dependencies,
						( d ) => d.kind === 'feature-component'
					),
				],
				[
					'… WordPress/React platform packages',
					count( dependencies, ( d ) => d.kind === 'platform' ),
				],
				[
					'… recovered LMS-owned modules',
					count( dependencies, ( d ) => d.kind === 'lms-module' ),
				],
				[
					'… recovered vendor libraries',
					count( dependencies, ( d ) => d.kind === 'vendor' ),
				],
				[
					'… recovered code in factory 1841',
					count( live, ( d ) => d.kind === 'recovered-local' ),
				],
				[
					'… inlined Babel helpers (removed by authoring)',
					count( dependencies, ( d ) => d.owner === 'build tooling' ),
				],
				[
					'Unassigned bindings',
					count( dependencies, ( d ) => d.owner === 'unassigned' ),
				],
				[ 'Recovered library families', libraries.length ],
			]
		),
		'',
		'The classification is heuristic: it uses source signatures, fragment names and consumer counts.',
		'`tests/js/runtime-inventory.test.mjs` fails if a binding loses its owner, or if this file',
		'drifts from the source.',
		'',
		'## By roadmap step',
		'',
		table(
			[ 'Step', 'Work', 'Bindings' ],
			Object.entries( roadmapSteps ).map( ( [ step, label ] ) => [
				step,
				label,
				count( dependencies, ( d ) => String( d.step ) === step ),
			] )
		),
		'',
		'## Unwired feature copies',
		'',
		'These folders have a `components.json`, but no extension loader imports them, so they are',
		'not part of the build. They are left out of every count below. Retire them, or wire them in',
		'and remove the copy they duplicate.',
		'',
		table(
			[ 'Folder', 'Components' ],
			inventory.unwired.map( ( entry ) => [
				code( `assets/src/features/${ entry.feature }` ),
				entry.components,
			] )
		),
		'',
		'## By feature',
		'',
		'Bindings each feature still reads. A feature is independent (step 5) once every column except',
		'Platform is zero and its components no longer use `createComponent(readRuntime)`.',
		'',
		table(
			[
				'Feature',
				'Components',
				'Platform',
				'Shared',
				'State/API',
				'Vendor',
				'Other features',
				'Own recovered',
				'Babel helpers',
			],
			features.map( ( feature ) => {
				const own = dependencies.filter( ( d ) =>
					d.consumers.includes( feature )
				);
				return [
					feature,
					count( components, ( c ) => c.feature === feature ),
					count( own, ( d ) => d.kind === 'platform' ),
					count(
						own,
						( d ) =>
							d.owner === 'shared-infrastructure' && d.step === 3
					),
					count( own, ( d ) => d.step === 4 ),
					count( own, ( d ) => d.kind === 'vendor' ),
					count(
						own,
						( d ) =>
							d.kind === 'feature-component' &&
							d.feature !== feature
					),
					count(
						own,
						( d ) =>
							d.kind === 'recovered-local' &&
							d.owner === feature &&
							d.step === 5
					),
					count( own, ( d ) => d.owner === 'build tooling' ),
				];
			} )
		),
		'',
		'## Shared application infrastructure (step 3)',
		'',
		'These are platform packages, recovered LMS-owned modules, or recovered code that more than one',
		'feature reads. Each becomes a direct import or a named public module.',
		'',
		table(
			[ 'Binding', 'Resolves to', 'Features', 'Target' ],
			live
				.filter(
					( d ) =>
						( d.owner === 'shared-infrastructure' &&
							d.step === 3 ) ||
						d.kind === 'platform'
				)
				.sort(
					( a, b ) =>
						b.consumers.length - a.consumers.length ||
						a.binding.localeCompare( b.binding )
				)
				.map( ( d ) => [
					code( d.binding ),
					describe( d ),
					d.consumers.length,
					ownerTargets[ d.owner ],
				] )
		),
		'',
		'## State and API access (step 4)',
		'',
		'The application data store and REST client (factory 86169, binding `T`) is the largest single',
		'dependency. Most features read it. Splitting it into per-feature stores and API clients is the',
		'core of step 4. The recovered code below also calls the REST API or creates state directly.',
		'',
		table(
			[ 'Binding', 'Resolves to', 'Owner', 'Used by' ],
			live
				.filter( ( d ) => d.step === 4 )
				.map( ( d ) => [
					code( d.binding ),
					describe( d ),
					d.owner,
					d.usedBy.join( ', ' ),
				] )
		),
		'',
		'## Recovered libraries (step 2)',
		'',
		'Every third-party family still registered by shipped bundles, consumed or not.',
		'',
		table(
			[ 'Library', 'Factories', 'Size', 'Bundles', 'Bridged by', 'Plan' ],
			libraries.map( ( library ) => [
				library.library,
				library.factories,
				kb( library.bytes ),
				library.bundles.join( ', ' ),
				library.bridged.join( ', ' ) || '—',
				libraryPlans[ library.library ] || 'Identify and assign.',
			] )
		),
		'',
		'Vendor bindings that features read directly:',
		'',
		table(
			[ 'Binding', 'Library', 'Features' ],
			live
				.filter( ( d ) => d.kind === 'vendor' )
				.map( ( d ) => [
					code( d.binding ),
					describe( d ),
					d.consumers.join( ', ' ),
				] )
		),
		'',
		'## Cross-feature component use',
		'',
		'These authored components are read by another feature through the runtime. Step 10 forbids',
		'that unless the read goes through a documented public export.',
		'',
		table(
			[ 'Component', 'Read by' ],
			live
				.filter(
					( d ) =>
						d.kind === 'feature-component' &&
						d.consumers.some( ( feature ) => feature !== d.feature )
				)
				.map( ( d ) => [
					describe( d ),
					d.consumers
						.filter( ( feature ) => feature !== d.feature )
						.join( ', ' ),
				] )
		),
		'',
		'## Recovered entry point and routes (step 6)',
		'',
		'Factory 1841 is still the production entry point. Its router mounts these screens. The',
		'authored bootstrap must register the same paths before the numeric factories and',
		'compatibility adapters can go.',
		'',
		table(
			[ 'Route', 'Binding', 'Mounted screen' ],
			inventory.routes.map( ( route ) => [
				code( route.route ),
				code( route.binding ),
				route.kind === 'feature-component'
					? `authored: ${ route.feature }/${ route.component }`
					: route.fragment
						? `recovered: ${ path.basename( route.fragment ) }`
						: `not in factory 1841 (${ route.kind })`,
			] )
		),
		'',
		'## Per-feature recovered code (step 5)',
		'',
		'Each of these recovered locals is used by one feature, or belongs to one by fragment. Each',
		'moves into that feature as an authored module.',
		'',
	];
	for ( const feature of [
		...new Set( [ ...features, 'bootstrap' ] ),
	].sort() ) {
		const rows = live.filter(
			( d ) =>
				d.kind === 'recovered-local' &&
				d.owner === feature &&
				d.step !== 4
		);
		if ( ! rows.length ) continue;
		lines.push(
			`### ${ feature }`,
			'',
			table(
				[ 'Binding', 'Kind', 'Fragment', 'Size', 'Used by' ],
				rows.map( ( d ) => [
					code( d.binding ),
					d.purpose,
					path.basename( d.fragment || '' ),
					`${ d.bytes.toLocaleString( 'en-US' ) } B`,
					d.usedBy
						.map( ( user ) => user.split( '/' )[ 1 ] )
						.join( ', ' ),
				] )
			),
			''
		);
	}
	const helpers = Object.entries(
		dependencies
			.filter( ( d ) => d.owner === 'build tooling' )
			.reduce(
				( map, d ) => ( {
					...map,
					[ d.purpose ]: ( map[ d.purpose ] || 0 ) + 1,
				} ),
				{}
			)
	).sort( ( a, b ) => b[ 1 ] - a[ 1 ] || a[ 0 ].localeCompare( b[ 0 ] ) );
	lines.push(
		'## Inlined Babel helpers',
		'',
		'These are not real dependencies. Each recovered module carried its own copy of these compiler',
		'helpers, and they go away when a component is authored as normal JSX.',
		'',
		table(
			[ 'Helper', 'Bindings' ],
			helpers.map( ( [ name, total ] ) => [
				name.replace( 'babel:', '' ),
				total,
			] )
		),
		''
	);
	return lines.join( '\n' );
}

if (
	process.argv[ 1 ] &&
	import.meta.url === pathToFileURL( process.argv[ 1 ] ).href
) {
	const root = path.resolve( import.meta.dirname, '..' );
	const inventory = buildInventory( root );
	const report = path.join( root, reportPath );
	const json = path.join( root, 'build/runtime-inventory.json' );
	fs.mkdirSync( path.dirname( json ), { recursive: true } );
	fs.writeFileSync( json, JSON.stringify( inventory, null, '\t' ) + '\n' );
	const markdown = renderInventory( inventory );
	if ( process.argv.includes( '--write' ) ) {
		fs.writeFileSync( report, markdown );
	} else if ( process.argv.includes( '--check' ) ) {
		const current = fs.existsSync( report )
			? fs.readFileSync( report, 'utf8' ).replace( /\r\n/g, '\n' )
			: '';
		if ( current !== markdown ) {
			console.error(
				`${ reportPath } is stale; run node tools/runtime-inventory-report.mjs --write`
			);
			process.exitCode = 1;
		}
	}
	console.log(
		`${ inventory.components.length } components, ${ inventory.dependencies.length } bindings, ${ inventory.libraries.length } library families`
	);
}
