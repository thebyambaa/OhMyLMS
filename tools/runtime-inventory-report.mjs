/** Renders docs/RUNTIME-DEPENDENCY-INVENTORY.md from the runtime inventory.
 * `--write` regenerates it, `--check` fails when it is stale. The full JSON goes to
 * build/runtime-inventory.json for ad hoc queries.
 */

