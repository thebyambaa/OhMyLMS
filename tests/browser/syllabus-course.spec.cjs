const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
const fixturePath = require('node:path').resolve('test-results/syllabus-course-session.json');
test.skip(!fs.existsSync(fixturePath), 'Requires the explicitly enabled syllabus course fixture.');

test('selects syllabus skills, reviews lessons and opens an independent draft', async ({ page, context }, testInfo) => {
  const state = JSON.parse(fs.readFileSync(fixturePath, 'utf8'));
  await context.addCookies(state.cookies);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${state.base}/wp-admin/admin.php?page=ohmylms#/content-hub/curriculum/syllabus/${state.syllabus}`);
  await page.getByRole('button', { name: 'Create course from syllabus', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Create course from syllabus', exact: true });
  await expect(dialog.getByLabel('Course title')).toHaveValue('Course generation syllabus');
  await dialog.getByLabel('Course title').fill(state.browser_title);
  await dialog.getByRole('button', { name: 'Clear selection', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Review course outline', exact: true })).toBeDisabled();
  await dialog.getByLabel('All skills in Number', { exact: true }).check();
  await dialog.getByRole('button', { name: 'Review course outline', exact: true }).click();
  await expect(dialog.getByText('1 unit · 1 lesson · 2 skills', { exact: true })).toBeVisible();
  await expect(dialog.getByText('Number foundations')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('syllabus-course-review.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Create draft course', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Course outline', exact: true })).toBeVisible();
  expect(page.url()).toContain('/course-edit/');
  const tree = page.getByRole('navigation', { name: 'Units, lessons and activities' });
  await tree.getByRole('button', { name: 'Number foundations', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Linked skills', exact: true })).toBeVisible();
  const course = Number(page.url().match(/course-edit\/(\d+)/)[1]);
  const snapshot = await page.evaluate(id => wp.apiFetch({ path: `/ohmylms/v1/courses/${id}/structure` }), course);
  expect(snapshot.program.outcomes).toHaveLength(2);
  expect(snapshot.program.groups).toHaveLength(1);
  expect(snapshot.program.items).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath('syllabus-generated-course.png'), fullPage: true });

  const checklist = page.locator('.ohmylms-outline-readiness');
  await page.getByRole('tab', { name: /^Readiness/ }).click();
  await checklist.locator('summary').click();
  await expect(checklist.getByText('Needs activities.', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Outline', exact: true }).click();
  const rememberResource = async responsePromise => {
    const response = await responsePromise;
    expect(response.ok()).toBe(true);
    const resource = await response.json();
    state.resources = [...(state.resources || []), resource.id];
    fs.writeFileSync(fixturePath, JSON.stringify(state));
    return resource;
  };
  const resourceResponse = () => page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith(`/courses/${course}/structure/resources`));
  const createDraft = async (button, title, fill) => {
    await tree.getByRole('button', { name: 'Number foundations', exact: true }).click();
    await page.getByRole('button', { name: button, exact: true }).click();
    const composer = page.getByRole('dialog', { name: 'Add activity', exact: true });
    await composer.getByLabel('New activity title').fill(title);
    await fill(composer);
    const response = resourceResponse();
    await composer.getByRole('button', { name: 'Create draft activity', exact: true }).click();
    await rememberResource(response);
    await expect(composer).not.toBeVisible();
  };
  await createDraft('Add reading', 'Read numbers', async composer => {
    await composer.getByLabel('Reading content').fill('<p>Read and compare numbers.</p>');
  });
  const teaching = page.getByRole('group', { name: 'Skills taught by this activity' });
  await teaching.getByRole('checkbox').nth(0).check();
  await teaching.getByRole('checkbox').nth(1).check();
  await expect(checklist.getByText(/^Skills to teach:/)).toHaveCount(0);
  let unsaved = await page.evaluate(id => wp.apiFetch({ path: `/ohmylms/v1/courses/${id}/structure` }), course);
  expect(unsaved.program.items).toEqual([]);
  await tree.getByRole('button', { name: 'Number foundations', exact: true }).click();
  await page.getByRole('button', { name: 'Add practice', exact: true }).click();
  const practice = page.getByRole('dialog', { name: 'Add activity', exact: true });
  await expect(practice.getByRole('button', { name: /^Add Number/ })).toHaveCount(2);
  await practice.getByRole('button', { name: /^Add Number first/ }).click();
  await createDraft('Add quiz', 'Check numbers', async () => {});
  const assessment = page.getByRole('group', { name: 'Skills assessed by this activity' });
  await assessment.getByRole('checkbox').nth(0).check();
  await assessment.getByRole('checkbox').nth(1).check();
  await expect(checklist.getByText(/^Skills to assess:/)).toHaveCount(0);
  await createDraft('Add video', 'Watch numbers', async composer => {
    await composer.getByLabel('Video URL').fill('https://example.com/lesson.mp4');
    await composer.getByLabel('Video notes').fill('Watch how numbers compare.');
  });
  await page.getByRole('group', { name: 'Skills taught by this activity' }).getByRole('checkbox').nth(0).check();
  await page.getByRole('button', { name: 'Save outline draft', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Course outline editor' }).getByText('Outline draft saved.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Reload saved outline', exact: true }).click();
  await expect(tree.getByRole('button', { name: 'Read numbers', exact: true })).toBeVisible();
  const saved = await page.evaluate(id => wp.apiFetch({ path: `/ohmylms/v1/courses/${id}/structure` }), course);
  expect(saved.program.items).toHaveLength(4);
  expect(saved.program.items.find(item => item.name === 'Read numbers').skill_ids).toHaveLength(2);
  expect(saved.program.items.find(item => item.type === 'quiz').skill_ids).toHaveLength(2);
  expect(saved.program.items.find(item => item.type === 'practice').group_id).toBe(saved.program.groups[0].id);
  await page.getByRole('tab', { name: /^Readiness/ }).click();
  await checklist.locator('summary').click();
  await expect(checklist.getByText('Publish the draft resources before publishing the outline.', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Outline', exact: true }).click();
  await tree.getByRole('button', { name: 'Number', exact: true }).click();
  await page.getByRole('button', { name: 'Add lesson', exact: true }).click();
  await page.getByLabel('Lesson title', { exact: true }).fill('Extra skills lesson');
  await page.getByRole('button', { name: 'Link skills to lesson', exact: true }).click();
  const skills = page.getByRole('dialog', { name: 'Link skills to lesson', exact: true });
  await skills.getByLabel('Find a skill', { exact: true }).fill('Algebra first');
  await skills.getByRole('button', { name: /^Add Algebra first/ }).click();
  await expect(skills).not.toBeVisible();
  await page.getByRole('button', { name: 'Add practice', exact: true }).click();
  const linkedPractice = page.getByRole('dialog', { name: 'Add activity', exact: true });
  await linkedPractice.getByRole('button', { name: /^Add Algebra first/ }).click();
  await page.getByRole('button', { name: 'Save outline draft', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Course outline editor' }).getByText('Outline draft saved.', { exact: true })).toBeVisible();
  const linked = await page.evaluate(id => wp.apiFetch({ path: `/ohmylms/v1/courses/${id}/structure` }), course);
  expect(linked.program.groups).toHaveLength(2);
  expect(linked.program.items).toHaveLength(5);
  expect(linked.program.outcomes).toHaveLength(3);
  expect(linked.program.outcomes.find(row => row.group_id === linked.program.groups[1].id).required).toBe(false);
  await page.getByRole('tab', { name: 'Syllabus alignment', exact: true }).click();
  await expect(page.getByText('2 objectives, 2 with content linked', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('lesson-activities-checklist.png'), fullPage: true });
  expect(errors).toEqual([]);
});
