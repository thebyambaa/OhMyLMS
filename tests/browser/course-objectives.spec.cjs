const { test, expect } = require('@playwright/test');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
let state;
const php = process.env.OHMYLMS_PHP || 'php';
const phpArgs = ['-d', `extension_dir=${path.join(path.dirname(php), 'ext')}`, '-d', 'extension=mysqli', '-d', 'extension=mbstring', '-d', 'extension=openssl', '-d', 'memory_limit=512M'];
const fixture = (...args) => execFileSync(php, [...phpArgs, 'tests/php/course-objectives-integration.php', ...args], { encoding: 'utf8', windowsHide: true });
test.beforeAll(() => { state = JSON.parse(fixture('setup')); });
test.afterAll(() => { if (state) fixture('cleanup', JSON.stringify(state)); });

test('course objectives support search, persistence, failed saves and removal', async ({ page }, testInfo) => {
  const credentials = JSON.parse(fs.readFileSync(process.env.OHMYLMS_TEST_CREDENTIALS, 'utf8'));
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/wp-login.php');
  await page.locator('#user_login').fill(credentials.username);
  await page.locator('#user_pass').fill(credentials.password);
  await page.locator('#wp-submit').click();
  await page.waitForURL(/wp-admin/);
  await page.goto(`/wp-admin/admin.php?page=ohmylms#/course-edit/${state.course}/content`);
  await page.getByRole('tab', { name: 'Syllabus alignment', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Syllabus objectives', exact: true });
  await expect(panel.getByText('No target objectives selected yet.', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Add objectives', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Add syllabus objectives', exact: true });
  await dialog.getByLabel('Official syllabus / edition').selectOption(String(state.syllabus));
  await dialog.getByRole('checkbox', { name: /ALG-01/ }).check();
  await dialog.getByRole('searchbox').fill('Simplify');
  await dialog.getByRole('checkbox', { name: /ALG-02/ }).check();
  await expect(dialog.getByRole('status')).toHaveText('2 selected · limit 200 per course');
  await page.screenshot({ path: testInfo.outputPath('objective-picker.png'), fullPage: true });
  const endpoint = url => decodeURIComponent(url.toString()).includes(`/courses/${state.course}/syllabus-objectives`);
  await page.route(endpoint, route => route.request().method() !== 'GET' ? route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ code: 'test_save_failed', message: 'Simulated mapping failure', data: { status: 500 } }) }) : route.continue());
  await dialog.getByRole('button', { name: 'Add selected objectives' }).click();
  await expect(dialog.getByText('Simulated mapping failure', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('status')).toHaveText('2 selected · limit 200 per course');
  await page.unroute(endpoint);
  await dialog.getByRole('button', { name: 'Add selected objectives' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(panel.locator('tbody tr')).toHaveCount(2);
  await expect(panel.getByText('Lessons: 1 · assessment activities: 1', { exact: true })).toBeVisible();
  await panel.locator('summary').click();
  await expect(panel.getByText('Equation examples', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: 'Syllabus alignment', exact: true }).click();
  await expect(panel.locator('tbody tr')).toHaveCount(2);
  await page.screenshot({ path: testInfo.outputPath('objectives-table.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.getByRole('button', { name: 'Add objectives', exact: true }).click();
  await dialog.getByLabel('Official syllabus / edition').selectOption(String(state.syllabus));
  await expect(dialog.getByRole('checkbox', { name: /ALG-01/ })).toBeDisabled();
  const modalBounds = await dialog.boundingBox();
  expect(modalBounds.x).toBeGreaterThanOrEqual(0);
  expect(modalBounds.x + modalBounds.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath('objective-picker-mobile.png') });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await panel.getByRole('button', { name: 'Remove objective: Simplify expressions', exact: true }).click();
  await expect(panel.locator('tbody tr')).toHaveCount(1);
  await page.reload();
  await page.getByRole('tab', { name: 'Syllabus alignment', exact: true }).click();
  await expect(panel.locator('tbody tr')).toHaveCount(1);
  // Existing duplicated ProseMirror instances in the course description editor:
  // docs/DEVELOPMENT.md, Known issues. Keep every other page error actionable.
  const knownEditorError = 'Adding different instances of a keyed plugin (plugin$)';
  const known = errors.filter(message => message === knownEditorError);
  if (known.length) testInfo.annotations.push({ type: 'known-editor-error', description: `${known.length} existing ProseMirror instance errors; mapping interactions completed.` });
  expect(errors.filter(message => message !== knownEditorError)).toEqual([]);
});

