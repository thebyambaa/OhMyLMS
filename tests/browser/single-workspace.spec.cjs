const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
test('single workspace searches, edits connections, protects drafts and opens bulk tool', async ({ page, baseURL }) => {
  test.skip(baseURL !== 'http://127.0.0.1:8100', 'Requires disposable migration clone.');
  const credentials = JSON.parse(fs.readFileSync(process.env.OHMYLMS_TEST_CREDENTIALS, 'utf8'));
  await page.goto('/wp-login.php');
  await page.locator('#user_login').fill(credentials.username);
  await page.locator('#user_pass').fill(credentials.password);
  await page.locator('#wp-submit').click();
  await page.waitForURL(url => !url.pathname.endsWith('wp-login.php'));
  await page.goto('/wp-admin/admin.php?page=ohmylms');
  await page.waitForFunction(() => Boolean(window.wp?.apiFetch));
  const request = options => page.evaluate(async o => { try { return await wp.apiFetch(o); } catch(e) { throw new Error(JSON.stringify(e)); } }, options);
  const base='/ohmylms/v1';
  const make = async (path,data,method='POST') => request({path:base+'/'+path,method,data});
  const sourceItem=(await make('curriculum/items',{name:'Workspace test source',item_type:'syllabus',is_syllabus:true})).item;
  const roadmapItem=(await make('curriculum/items',{name:'Workspace test roadmap',item_type:'roadmap',is_syllabus:true})).item;
  const sourceGroup=await make(`curriculum/items/${sourceItem.id}/syllabus/groups`,{name:'Skills'});
  const sourceOutline=await make(`curriculum/items/${sourceItem.id}/syllabus/groups/${sourceGroup.group_id}/skills`,{name:'Source number types',code:'TEST1'});
  const sourceSkill=sourceOutline.contents.flatMap(c=>c.groups).flatMap(g=>g.skills)[0];
  const shared=await make('syllabus-comparison/shared-skills/save',{name:'Types of number',subject:'Mathematics',description:'Identify number types'});
  await make(`curriculum/items/${roadmapItem.id}/syllabus/groups`,{name:'Numbers'});
  const road=await request({path:base+`/syllabus-comparison/roadmaps/${roadmapItem.id}`});
  await make(`syllabus-comparison/roadmaps/${roadmapItem.id}`,{name:road.name,syllabus_ids:[sourceItem.id],skill_ids:[shared.id],folders:road.folders.map((folder,index)=>({...folder,skill_ids:index===0?[shared.id]:[]})),expected_revision:road.revision},'PUT');
  await make('syllabus-comparison/mapping',{specific_id:sourceSkill.term_id,shared_id:shared.id,relation:'narrower',note:'Original note',expected_revision:''},'PUT');
  await page.goto(`/wp-admin/admin.php?page=ohmylms#/content-hub/curriculum/syllabus/${roadmapItem.id}`);
  await expect(page.getByRole('button', {name:'Bulk edit',exact:true})).toBeVisible({timeout:30000});
  await expect(page.getByRole('button', {name:'Mind map',exact:true})).toHaveCount(0);
  await page.getByLabel('Search skills',{exact:true}).fill('Types of number');
  const skill = page.locator('.ohmylms-ws-node.is-skill .ohmylms-ws-node-main').first();
  await expect(skill).toBeVisible(); await skill.click();
  const panel = page.getByRole('region',{name:'Connections',exact:true});
  await expect(panel.getByRole('button',{name:'Edit connection',exact:true}).first()).toBeVisible();
  await panel.getByRole('button',{name:'Edit connection',exact:true}).first().click();
  const note = panel.getByLabel('Connection notes',{exact:true});
  const original = await note.inputValue();
  const marker = 'Workspace browser verification '+Date.now();
  try {
    await note.fill(marker);
    await expect(page.getByRole('button',{name:'Bulk edit',exact:true})).toBeDisabled();
    await panel.getByRole('button',{name:'Save connection',exact:true}).click();
    await expect(panel.getByText(marker,{exact:true})).toBeVisible({timeout:20000});
    await page.reload();
    await page.getByLabel('Search skills',{exact:true}).fill('Types of number'); await skill.click();
    await expect(panel.getByText(marker,{exact:true})).toBeVisible();
  } finally {
    if (await panel.getByRole('button',{name:'Discard edits',exact:true}).count()) await panel.getByRole('button',{name:'Discard edits',exact:true}).click();
    await panel.getByRole('button',{name:'Edit connection',exact:true}).first().click();
    await note.fill(original); await panel.getByRole('button',{name:'Save connection',exact:true}).click();
    await expect(panel.getByRole('button',{name:'Save connection',exact:true})).toHaveCount(0);
  }
  await panel.getByRole('button',{name:'Show connection diagram',exact:true}).click();
  await expect(panel.locator('.ohmylms-studio-stage')).toBeVisible();
  await panel.getByRole('button',{name:'Connect skill',exact:true}).click();
  await expect(panel.getByLabel('Source syllabus',{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'Discard edits',exact:true}).click();
  await panel.getByRole('button',{name:'Edit connection',exact:true}).first().click();
  await panel.getByRole('button',{name:'Remove connection',exact:true}).click();
  await expect(panel.getByText('No connected skills yet.',{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'Connect skill',exact:true}).click();
  await panel.getByRole('button',{name:'Select',exact:true}).first().click();
  await panel.getByLabel('Connection type (source relative to shared skill)',{exact:true}).selectOption('narrower');
  await panel.getByRole('button',{name:'Save connection',exact:true}).click();
  await expect(panel.getByRole('button',{name:'Edit connection',exact:true})).toHaveCount(1);
  const destination=await make(`curriculum/items/${roadmapItem.id}/syllabus/groups`,{name:'Moved skills'});
  await page.reload();
  await page.getByLabel('Search skills',{exact:true}).fill('Types of number');
  await page.getByRole('checkbox',{name:'Select Types of number for bulk move',exact:true}).check();
  await page.getByLabel('Move selected skills to',{exact:true}).selectOption(String(destination.group_id));
  await page.getByRole('button',{name:'Move selected',exact:true}).click();
  await expect(page.getByRole('button',{name:'Move selected',exact:true})).toHaveCount(0);
  const afterMove=await request({path:base+`/curriculum/items/${roadmapItem.id}/syllabus`});
  expect(afterMove.contents.flatMap(c=>c.groups).find(g=>g.id===destination.group_id).skills.map(s=>s.term_id)).toContain(shared.id);
  await page.getByRole('button',{name:'Bulk edit',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Bulk edit skills',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Return to workspace',exact:true}).click();
  await expect(skill).toBeVisible();
  await make(`curriculum/items/${roadmapItem.id}`,{children:'delete',confirm:true},'DELETE');
  await make(`curriculum/items/${sourceItem.id}`,{children:'delete',confirm:true},'DELETE');
  for (const id of [shared.id,sourceSkill.term_id]) await make(`skills/${id}`,{force:true},'DELETE');
});
